// Le département d'un code postal français (« 69003 » ⇒ « 69 », « 20090 » ⇒ « 2A », « 97411 » ⇒ « 974 »).
// Une forme qui n'est pas un code postal français ⇒ null (jamais deviné).
export function departementDuCp(cp) {
  const s = String(cp == null ? '' : cp).replace(/\s+/g, '');
  if (!/^\d{5}$/.test(s)) return null;
  if (s.startsWith('97')) return PREFECTURES[s.slice(0, 3)] ? s.slice(0, 3) : null;
  if (s.startsWith('20')) return Number(s.slice(0, 3)) <= 201 ? '2A' : '2B';
  return PREFECTURES[s.slice(0, 2)] ? s.slice(0, 2) : null;
}
