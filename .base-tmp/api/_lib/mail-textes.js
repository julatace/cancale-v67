// La phrase d'une clé dans la langue (repli : le français, jamais une clé brute).
export function tm(langue, cle, vars = {}) {
  const l = langueMail(langue);
  const s = (TEXTES_MAIL[l] && TEXTES_MAIL[l][cle]) || TEXTES_MAIL.fr[cle] || '';
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
}
// Le singulier ou le pluriel (`cle_1` / `cle_n`) ; {n} est posé.
export const tmN = (langue, cle, n, vars = {}) => tm(langue, `${cle}_${Number(n) === 1 ? '1' : 'n'}`, { n, ...vars });
