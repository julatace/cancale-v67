export const LANGUES_MAIL = ['fr', 'en', 'es', 'it', 'de'];
export const LOCALES_MAIL = { fr: 'fr-FR', en: 'en-GB', es: 'es-ES', it: 'it-IT', de: 'de-DE' };
// Une langue sûre : les cinq, sinon le français (jamais une erreur).
export const langueMail = (l) => { const x = String(l == null ? '' : l).toLowerCase().slice(0, 2); return LANGUES_MAIL.includes(x) ? x : 'fr'; };

// ── Les montants ────────────────────────────────────────────────────────────
// Le français : exactement l'ancienne règle d'api/_lib/bilan-mois.js (`euros`).
export const eurosFr = (x) => {
  const c = Math.round(Number(x) * 100); if (!Number.isFinite(c)) return '—';
  const n = Math.abs(c);
  return (c < 0 ? '−' : '') + String(Math.floor(n / 100)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ',' + String(n % 100).padStart(2, '0') + ' €';
};
export function eurosMail(x, langue = 'fr') {
  const l = langueMail(langue);
  if (l === 'fr') return eurosFr(x);
  const v = Number(x);
  if (x == null || x === '' || !Number.isFinite(v)) return '—';
  try { return new Intl.NumberFormat(LOCALES_MAIL[l], { style: 'currency', currency: 'EUR' }).format(Math.round(v * 100) / 100); } catch (_) { return eurosFr(x); }
}

// ── Les dates (heure de Paris) ──────────────────────────────────────────────
export function dateMail(ms, langue = 'fr', opts = { day: 'numeric', month: 'long' }) {
  const t = Number(ms);
  if (!Number.isFinite(t)) return '';
  try { return new Date(t).toLocaleDateString(LOCALES_MAIL[langueMail(langue)], { timeZone: 'Europe/Paris', ...opts }); } catch (_) { return ''; }
}
// « octobre 2026 », « October 2026 », « ottobre 2026 »… depuis « 2026-10 ».
export function moisMail(ym, langue = 'fr') {
  const m = /^(\d{4})-(\d{2})$/.exec(String(ym || ''));
  if (!m) return '';
  return dateMail(Date.UTC(Number(m[1]), Number(m[2]) - 1, 15, 12), langue, { month: 'long', year: 'numeric' });
}

