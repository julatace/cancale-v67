// AUDIT · les règles pures de Ventes / Achats « Verre dépoli » (src/ventesVerre.js), 15 nov.
//   C  la sélection d'office = la règle du lot (`cochesParDefaut`) ; décocher / recocher ; eBay ne bouge jamais ;
//   E  la place vient du Stock (`ouDansMeubles`) ; rien lu ⇒ null, jamais une place devinée ;
//   R  les quatre étapes d'un colis parti, cochées sur preuve ; une preuve plus loin coche celles d'avant ;
//   F  les six étapes de la fiche ; « À déposer » est le geste quand le bordereau est là et rien ne prouve le dépôt ;
//   T  les étapes d'un retour, de l'étape de src/retoursAchat.js.
'use strict';
const path = require('path');
let ok = 0, ko = 0;
const dit = (c, m, d) => { if (c) ok++; else ko++; console.log((c ? '✅ ' : '❌ ') + m + (c || d == null ? '' : ' — ' + JSON.stringify(d))); };
(async () => {
  const R = await import(path.join(__dirname, '..', 'src', 'ventesVerre.js'));
  const L = [{ cle: 'a', pdf: true }, { cle: 'b', pdf: true, imprime: 1 }, { cle: 'c', pdf: false }, { cle: 'e', cochable: false, pdf: false }, { cle: 'f', pdf: true, ancienne: true }];
  const d = R.cochesEffectives(L, null);
  dit([...d].join() === 'a', 'C d\'office : le bordereau là, pas imprimé, pas ancien', [...d]);
  const s1 = R.basculerCoche(L, null, 'a'); dit(s1.size === 0, 'C décocher', [...s1]);
  const s2 = R.basculerCoche(L, s1, 'b'); dit([...s2].join() === 'b', 'C cocher un déjà imprimé (son choix)', [...s2]);
  const s3 = R.basculerCoche(L, s2, 'e'); dit([...s3].join() === 'b', 'C eBay ne se coche jamais', [...s3]);
  dit(R.memeQueDefaut(L, null) && R.memeQueDefaut(L, new Set(['a'])) && !R.memeQueDefaut(L, new Set(['b'])), 'C la sélection d\'office se reconnaît');
  dit([...R.cochesEffectives([{ cle: 'a', pdf: true }], new Set(['a', 'parti']))].join() === 'a', 'C un colis parti sort de la sélection');
  dit(JSON.stringify(R.emplacementDe({ meuble: { name: 'Étagère A' }, rangee: 1, colonne: 3 })) === '{"nom":"Étagère A","rangee":1,"colonne":3}', 'E la place lue');
  dit(R.emplacementDe(null) === null && R.emplacementDe({ meuble: null }) === null && R.emplacementDe({ meuble: {}, rangee: NaN, colonne: 1 }) === null, 'E rien lu ⇒ null');
  const r = (l) => R.etapesRoute(l).map((e) => (e.fait ? '1' : '0') + (e.ici ? '*' : '')).join(',');
  dit(r({ depose: true }) === '1*,0,0,0', 'R déposé seul', r({ depose: true }));
  dit(r({ depose: true, enroute: true }) === '1,1*,0,0', 'R en transit', r({ depose: true, enroute: true }));
  dit(r({ livre: true }) === '1,1,1*,0', 'R livré prouvé coche les étapes d\'avant', r({ livre: true }));
  dit(r({}) === '0,0,0,0', 'R rien prouvé ⇒ rien coché', r({}));
  const fr = (f) => R.etapesFicheVente(f).map((e) => (e.fait ? '1' : '0') + (e.geste ? '!' : e.ici ? '*' : '')).join(',');
  const F = (v, b, dd, l, a) => [{ cle: 'vendue', fait: v }, { cle: 'bordereau', fait: b }, { cle: 'deposee', fait: dd }, { cle: 'livree', fait: l }, { cle: 'argent', fait: a }];
  dit(fr(F(true, true, false, false, false)) === '1,1,0!,0,0,0', 'F bordereau prêt ⇒ « À déposer » en geste', fr(F(true, true, false, false, false)));
  dit(fr(F(true, false, false, false, false)) === '1,0*,0,0,0,0', 'F sans bordereau : le bordereau est attendu, pas un geste', fr(F(true, false, false, false, false)));
  dit(fr(F(true, true, true, false, false)) === '1,1,1,1,0*,0', 'F déposé ⇒ en route, livraison attendue', fr(F(true, true, true, false, false)));
  dit(fr(F(true, true, true, true, true)) === '1,1,1,1,1,1', 'F versée ⇒ tout fait');
  dit(R.etapesFicheVente(null) === null, 'F hors parcours ⇒ rien');
  const t = (c) => R.etapesRetour(c).map((e) => (e.fait ? '1' : '0') + (e.geste ? '!' : e.ici ? '*' : '')).join(',');
  dit(t({ etape: 'a-deposer', pdf: true }) === '1,1,0!,0,0', 'T à déposer avec bordereau', t({ etape: 'a-deposer', pdf: true }));
  dit(t({ etape: 'a-deposer', pdf: false }) === '1,0*,0,0,0', 'T sans bordereau', t({ etape: 'a-deposer', pdf: false }));
  dit(t({ etape: 'rembourse', pdf: true }) === '1,1,1,1,1', 'T remboursé');
  dit(R.etapesRetour({ etape: 'inconnue' }) === null, 'T étape inconnue ⇒ rien');
  console.log(ko ? `\n❌ audit-ventes-verre : ${ko} rouge(s), ${ok} vert(s)` : `\n✅ audit-ventes-verre : ${ok} verts`);
  process.exit(ko ? 1 : 0);
})();
